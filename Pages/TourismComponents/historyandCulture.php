                    <div class="mt-3" style="color:#00489a;">
                      <h4>Imus Historical Museum</h4>
                      <p>This fortress-like structure was once a metal foundry and workshop operated by Jose Ignacio Paua – a blacksmith of Chinese descent who made guns and cannons and repaired them for the revolutionaries. A plaque outside the building proclaims it as the “Arsenal ng Imus.”

Inside the museum is a series of moving tableaus that take visitors back through time to relive historical scenes with realistic life-size figures set amidst painstakingly recreated settings.

Each scene is set in motion with the help of hidden sensors, while informative and well-written captions present the facts surrounding each episode. Interspersed between these tableaus are colorfully detailed murals and relief sculptures of crucial figures in the Cavite Revolution, as well as fascinating trivia and little-known historical tidbits.

Combining creativity and modern technology, the Imus Historical Museum presents an eye-opening view of local history in an appealing, more exciting light to increase the awareness and pride of the Filipinos in their nation’s history and patrimony.</p>
