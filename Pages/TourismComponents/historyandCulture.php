                    <div class="mt-3" style="color:#00489a;">
                      <h4>Battle of Alapan</h4>
                      <p>The Battle of Alapan paved the way for the birth of the First Philippine Republic. It is where the Philippine Flag, sewn in Hongkong by Marcella Agoncillo, received its Baptism on Fire on May 28, 1898. Located at the Alapan I Elementary School, the battle site is a 10-15 minute drive from the town proper. The location of this marker was highlighted by a 104 feet tall flagpole where the Philippine Flag proudly waves. The marker is set atop three large rocks, each encrusted with pasted cement. On the center of the rock is a statue of a woman boldly holding the Philippine Flag. The National Historical Institute declared the site as a National Historical Landmark through Resolution Number 5 Series of 1993, signed on May 26, 1993.</p>
