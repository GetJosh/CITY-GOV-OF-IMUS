                      <p>Gawad Parangal commemorates the establishment of the Municipality of Imus, Cavite, on October 7, 1775, independent from Cavite El Viejo (now Kawit). In this annual celebration, outstanding citizens of Imus are also conferred honors in the Gawad Parangal.
<br>
Gawad Parangal Awards include: <br>

Gen. Licerio Topacio Award - the highest award given to Imuseños, who have achieved something extra special for the people of Imus. <br>

Gen. Juan Castañeda Award - this award is given to outstanding Imuseños in their chosen field of endeavor (Arts, Sciences, Medicine, History, Entrepreneurship, etc.) <br>

Gen. Pantaleon Garcia Award - this is awarded to an outstanding public servant, nominated by their peers. <br>

Gen. Cayetano P. Topacio Award - an award extended to outstanding students. <br>

Col. Jose S. Tagle Award - this is the young achiever’s award given to Imuseños, aged 39 years old and below who achieved something extraordinary. <br>

Gen. Flaviano A. Yengco Award - this is the award given to investors who have been partners of the municipality in business. This includes the Outstanding Taxpayers’ Award, Investor’s Award, and Posthumous Award</p> <br>
